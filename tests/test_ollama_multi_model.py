"""Unit tests for Dynamic Ollama Multi-Model Registry & Switcher."""
import json
import unittest
from unittest.mock import MagicMock, patch

from jarvis_os.primitives.ollama_registry import OllamaModelRegistry
from jarvis_os.primitives.engine import InferenceEngine
from server.llm.router import ModelRouter
from server.llm.ollama import OllamaClient


class TestOllamaMultiModelSwitcher(unittest.TestCase):
    def setUp(self):
        self.fake_tags_response = {
            "models": [
                {
                    "name": "qwen2.5-coder:14b",
                    "size": int(9.0 * (1024 ** 3)),
                    "modified_at": "2026-10-15T10:00:00Z",
                    "details": {"family": "qwen2", "parameter_size": "14.8B", "quantization_level": "Q4_K_M"},
                },
                {
                    "name": "deepseek-r1:8b",
                    "size": int(4.9 * (1024 ** 3)),
                    "modified_at": "2026-10-16T12:00:00Z",
                    "details": {"family": "llama", "parameter_size": "8.0B", "quantization_level": "Q4_K_M"},
                },
                {
                    "name": "llama3.2:3b",
                    "size": int(2.0 * (1024 ** 3)),
                    "modified_at": "2026-10-17T08:00:00Z",
                    "details": {"family": "llama", "parameter_size": "3.2B", "quantization_level": "Q4_K_M"},
                },
                {
                    "name": "llava:7b",
                    "size": int(4.7 * (1024 ** 3)),
                    "modified_at": "2026-10-17T09:00:00Z",
                    "details": {"family": "llava", "parameter_size": "7B", "quantization_level": "Q4_0"},
                },
            ]
        }
        self.last_chat_payload = None

        def fake_get(url, timeout=3.0):
            return self.fake_tags_response

        def fake_post(url, payload, timeout=60.0):
            self.last_chat_payload = payload
            return {
                "model": payload["model"],
                "message": {"role": "assistant", "content": f"Generated by {payload['model']}"},
                "eval_count": 42,
            }

        self.reg = OllamaModelRegistry(http_getter=fake_get, http_poster=fake_post)

    def test_discovers_all_downloaded_models_and_capabilities(self):
        st = self.reg.status()
        self.assertTrue(st["daemon_online"])
        self.assertEqual(st["installed_count"], 4)
        names = [m["name"] for m in st["installed_models"]]
        self.assertEqual(names, ["qwen2.5-coder:14b", "deepseek-r1:8b", "llava:7b", "llama3.2:3b"])
        model_map = {m["name"]: m for m in st["installed_models"]}
        self.assertIn("coding", model_map["qwen2.5-coder:14b"]["capabilities"])
        self.assertIn("reasoning", model_map["deepseek-r1:8b"]["capabilities"])
        self.assertIn("vision", model_map["llava:7b"]["capabilities"])

    def test_switch_global_model_and_per_dot_model(self):
        # Switch global model to deepseek-r1:8b
        self.reg.select_model("deepseek-r1:8b")
        self.assertEqual(self.reg.active_model, "deepseek-r1:8b")
        self.assertEqual(self.reg.get_model_for_dot("scout"), "deepseek-r1:8b")

        # Bind @forge specifically to qwen2.5-coder:14b and @scribe to llama3.2:3b
        self.reg.select_model("qwen2.5-coder:14b", dot_id="forge")
        self.reg.select_model("llama3.2:3b", dot_id="scribe")

        self.assertEqual(self.reg.get_model_for_dot("forge"), "qwen2.5-coder:14b")
        self.assertEqual(self.reg.get_model_for_dot("scribe"), "llama3.2:3b")
        self.assertEqual(self.reg.get_model_for_dot("scout"), "deepseek-r1:8b")

        # Verify chat_with_model routes each Dot to its bound Ollama model
        r_forge = self.reg.chat_with_model("Write a binary search", dot_id="forge")
        self.assertEqual(r_forge["model"], "qwen2.5-coder:14b")
        self.assertIn("qwen2.5-coder:14b", r_forge["content"])

        r_scribe = self.reg.chat_with_model("Summarize notes", dot_id="scribe")
        self.assertEqual(r_scribe["model"], "llama3.2:3b")
        self.assertIn("llama3.2:3b", r_scribe["content"])

    def test_cli_fallback_when_http_offline(self):
        def failing_get(url, timeout=3.0):
            raise RuntimeError("Connection refused")

        cli_output = (
            "NAME                    ID              SIZE      MODIFIED\n"
            "mistral:7b              61e88e884507    4.1 GB    2 days ago\n"
            "gemma2:9b               ff02c3702f32    5.4 GB    5 days ago\n"
        )
        reg_cli = OllamaModelRegistry(http_getter=failing_get, cli_runner=lambda cmd: cli_output)
        self.assertEqual(len(reg_cli.installed_models), 2)
        self.assertEqual(reg_cli.installed_models[0]["name"], "mistral:7b")
        self.assertEqual(reg_cli.active_model, "mistral:7b")

    def test_inference_engine_per_dot_model_generation(self):
        eng = InferenceEngine(registry=self.reg)
        self.reg.select_model("deepseek-r1:8b")
        self.reg.select_model("qwen2.5-coder:14b", dot_id="forge")

        # Arithmetic calculation (deterministic fast path) uses chosen model
        rec_calc = eng.generate("calculate 40 + 2", dot_role="Forge", dot_id="forge")
        self.assertEqual(rec_calc["model"], "qwen2.5-coder:14b")

        # Text generation uses dot-bound model
        rec_chat = eng.generate("Write a quicksort in python", dot_role="Forge", dot_id="forge")
        self.assertEqual(rec_chat["model"], "qwen2.5-coder:14b")

        rec_scout = eng.generate("Research market competitors", dot_role="Scout", dot_id="scout")
        self.assertEqual(rec_scout["model"], "deepseek-r1:8b")

    def test_model_router_dynamic_set_model(self):
        client = OllamaClient("http://127.0.0.1:11434", "qwen3:8b", 30.0)
        router = ModelRouter(client)
        self.assertEqual(router.get_model(), "qwen3:8b")

        # Change model dynamically
        router.set_model("deepseek-r1:8b")
        self.assertEqual(router.get_model(), "deepseek-r1:8b")
        self.assertEqual(router.client_for().model, "deepseek-r1:8b")


if __name__ == "__main__":
    unittest.main()
